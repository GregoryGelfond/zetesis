//! Maintained benchmark inputs with their independent source provenance.
//!
//! The original correctness catalog stays byte-identical. Additional workloads
//! join the same matrix through their sealed source bundles and typed contracts.

use std::path::Path;

use super::{
    Error, bundles,
    matrix::{Workload, WorkloadLimits},
};
use crate::examples;

const FAMILY_MANIFEST_SHA256: &str =
    "92a39c82c8bebb5f17323db9e61084f2b713628b574690bcc0312147395d3f26";
const VAELII_MANIFEST_SHA256: &str =
    "f057110412bffe057aa4823df2020adb50bbe7bede33c4a663040cd20f16f526";
const VAELII_EXACT_MANIFEST_SHA256: &str =
    "4d3c20133189f46128d0a487e536b3c6ee20cb1a3baf153415be7f20976080fa";

/// Assemble the original 94 cases, integrated Family Crossing, 13 of the 14
/// reconstructed Vaelii-shaped workloads (`sg1k` is in the `vaelii-slow`
/// supplement) and the 9 exact Vaelii test programs
/// in that order.
///
/// `root` is the examples directory containing `correctness`,
/// `family-crossing`, `vaelii-reconstructed` and `vaelii-exact`. All source
/// bytes and include spellings stay unchanged. The Vaelii-shaped workloads are
/// reconstructions generated by `vaelii-reconstructed/gen.py`, not Vaelii
/// artifacts; `vaelii-exact` transcribes programs from Vaelii's own tests.
/// Family Crossing requires fresh reference qualification, as other bundled
/// workloads do. Limits bound preparation; no solver is launched here.
///
/// # Errors
/// Refuses missing or changed sources, invalid contracts and preparation limits.
pub fn workloads(
    catalog: &examples::Corpus,
    root: &Path,
    limits: WorkloadLimits,
) -> Result<Vec<Workload>, Error> {
    let manifest = root.join("family-crossing/manifest.json");
    let mut workloads = catalog
        .cases()
        .iter()
        .map(|case| Workload::original(catalog, case.path(), limits))
        .collect::<Result<Vec<_>, _>>()?;
    workloads.extend(bundles::load_reviewed(
        &manifest,
        limits,
        FAMILY_MANIFEST_SHA256,
    )?);
    workloads.extend(bundles::load_reviewed(
        &root.join("vaelii-reconstructed/manifest.json"),
        limits,
        VAELII_MANIFEST_SHA256,
    )?);
    workloads.extend(bundles::load_reviewed(
        &root.join("vaelii-exact/manifest.json"),
        limits,
        VAELII_EXACT_MANIFEST_SHA256,
    )?);
    Ok(workloads)
}
